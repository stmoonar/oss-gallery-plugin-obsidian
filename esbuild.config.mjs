import esbuild from "esbuild";
import process from "process";
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import { builtinModules, createRequire } from 'node:module';
import { dirname, join } from "node:path";
import { inlinedPackageDirs, writeThirdPartyNotices } from "./scripts/third-party-notices.mjs";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const outfile = prod ? "dist/main.js" : "main.js";
const releaseAssets = ["manifest.json", "styles.css", "LICENSE"];

// Semantic search runtime (docs/semantic-search.md §8.5). These files are
// release assets downloaded on request; they are never bundled into main.js.
const SEMANTIC_WORKER_FILE = "semantic-worker.js";
const ORT_RUNTIME_FILES = [
	"ort-wasm-simd-threaded.asyncify.wasm",
	"ort-wasm-simd-threaded.asyncify.mjs",
];
const RUNTIME_MANIFEST_PATH = "src/semantic/assets.generated.ts";
// Licenses of everything in the worker bundle and the ORT files. A release
// asset next to them, not part of the hashed runtime manifest: it is not
// needed to run, and the worker banner points to it.
const NOTICES_FILE = "THIRD_PARTY_NOTICES.txt";
const WORKER_BANNER =
	`/*! OSS Gallery semantic search worker. Bundles @huggingface/transformers, onnxruntime-web, ` +
	`utif, pako and other open-source packages; licenses: ${NOTICES_FILE} in the release ` +
	`(https://github.com/stmoonar/oss-gallery-plugin-obsidian/releases). */`;

async function copyReleaseAssets() {
	await mkdir("dist", { recursive: true });
	await Promise.all(
		releaseAssets.map((asset) => copyFile(asset, join("dist", asset)))
	);
}

/** onnxruntime-web is a transitive dependency; resolve it from transformers.js. */
async function resolveOrtDistDir() {
	const transformersDir = await realpath(join("node_modules", "@huggingface", "transformers"));
	const require = createRequire(join(transformersDir, "package.json"));
	// The "./webgpu" export resolves to a file inside onnxruntime-web/dist.
	return dirname(require.resolve("onnxruntime-web/webgpu"));
}

async function describeFile(file) {
	const bytes = await readFile(join("dist", file));
	return {
		file,
		size: bytes.length,
		sha256: createHash("sha256").update(bytes).digest("hex"),
	};
}

/**
 * Write the runtime asset manifest compiled into main.js. It is regenerated on
 * every build from the files actually written to dist/, so the hashes shipped
 * in main.js always match the release assets built alongside it.
 */
async function writeRuntimeManifest(entries) {
	const body = entries
		.map((e) => `\t{ file: ${JSON.stringify(e.file)}, size: ${e.size}, sha256: ${JSON.stringify(e.sha256)} },`)
		.join("\n");
	const content =
`// GENERATED by esbuild.config.mjs on every build. Do not edit by hand.
// Hashes of the semantic search runtime release assets (dist/).

export interface GeneratedRuntimeFile {
\tfile: string;
\tsize: number;
\tsha256: string;
}

export const GENERATED_RUNTIME_FILES: readonly GeneratedRuntimeFile[] = [
${body}
];
`;
	let previous = "";
	try {
		previous = await readFile(RUNTIME_MANIFEST_PATH, "utf8");
	} catch {
		// first build
	}
	if (previous.replace(/\r\n/g, "\n") !== content) {
		await writeFile(RUNTIME_MANIFEST_PATH, content);
		console.log(`[semantic] updated ${RUNTIME_MANIFEST_PATH}`);
	}
}

async function buildSemanticRuntime() {
	await mkdir("dist", { recursive: true });
	const result = await esbuild.build({
		entryPoints: ["src/semantic/worker/entry.ts"],
		outfile: join("dist", SEMANTIC_WORKER_FILE),
		bundle: true,
		format: "iife",
		platform: "browser",
		target: "es2022",
		minify: true,
		// Smaller than \uXXXX escapes for non-ASCII text.
		charset: "utf8",
		// License texts go to THIRD_PARTY_NOTICES.txt instead (see below).
		legalComments: "none",
		banner: { js: WORKER_BANNER },
		metafile: true,
		logLevel: "warning",
		// Obsidian workers have nodeIntegrationInWorker, so transformers.js
		// would detect Node and take its Node code paths. Hide `process`.
		define: { process: "undefined" },
		plugins: [
			{
				// transformers.web.js keeps guarded `node:*` imports; stub them.
				name: "stub-node-builtins",
				setup(b) {
					b.onResolve({ filter: /^node:/ }, (a) => ({ path: a.path, namespace: "stub-node" }));
					b.onLoad({ filter: /.*/, namespace: "stub-node" }, () => ({ contents: "module.exports = {};", loader: "js" }));
				},
			},
		],
	});

	const ortDir = await resolveOrtDistDir();
	await Promise.all(
		ORT_RUNTIME_FILES.map((file) => copyFile(join(ortDir, file), join("dist", file)))
	);
	const transformersDir = await realpath(join("node_modules", "@huggingface", "transformers"));
	const noticed = await writeThirdPartyNotices(
		result.metafile,
		[dirname(ortDir), ...(await inlinedPackageDirs(transformersDir, "dist/transformers.web.js"))],
		join("dist", NOTICES_FILE)
	);
	console.log(`[semantic] ${NOTICES_FILE}: ${noticed.join(", ")}`);

	const entries = await Promise.all(
		[SEMANTIC_WORKER_FILE, ...ORT_RUNTIME_FILES].map(describeFile)
	);
	await writeRuntimeManifest(entries);
	for (const e of entries) {
		console.log(`[semantic] ${e.file} ${(e.size / 1024).toFixed(0)} KB`);
	}
}

// The runtime manifest is compiled into main.js, so build it first.
await buildSemanticRuntime();

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile,
	minify: prod,
	// Keep CJK locale strings as UTF-8 instead of 6-byte \uXXXX escapes.
	charset: "utf8",
	// Lets the production build check which modules went into main.js.
	metafile: prod,
});

/**
 * Worker-only code and dependencies (transformers.js, onnxruntime, UTIF.js,
 * pako, src/semantic/worker/) must never be bundled into main.js. Returns the
 * offending input paths from the esbuild metafile.
 */
function workerOnlyInputs(metafile) {
	const workerOnly = /(^|\/)node_modules\/(\.pnpm\/[^/]+\/node_modules\/)?(@huggingface\/transformers|onnxruntime-[^/]+|utif|pako)\/|(^|\/)src\/semantic\/worker\//;
	return Object.keys(metafile.inputs).filter((path) => workerOnly.test(path.replace(/\\/g, "/")));
}

if (prod) {
	const result = await context.rebuild();
	await copyReleaseAssets();
	const leaked = workerOnlyInputs(result.metafile);
	if (leaked.length > 0) {
		throw new Error(`main.js must not bundle worker-only code: ${leaked.join(", ")}`);
	}
	const mainJs = await readFile(outfile, "utf8");
	if (/@huggingface\/transformers|onnxruntime|PlanarConfiguration 2 should not be used|incorrect header check/.test(mainJs)) {
		throw new Error("main.js must not bundle transformers.js / onnxruntime / UTIF.js / pako");
	}
	process.exit(0);
} else {
	await context.watch();
}
